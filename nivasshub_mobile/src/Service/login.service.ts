import {
  HttpException,
  Injectable,
  InternalServerErrorException,
} from '@nestjs/common';
import { LoginRepository } from '../repositories/login.repository';
import {
  ForgotPasswordVerifyOtpRequest,
  ForgotPasswordVerifyOtpResponse,
  LoginProcedureRequest,
  LoginResponse,
  UpdatePasswordRequest,
  UpdatePasswordResponse,
} from '../types/login.types';
import {
  ForgetPasswordDto,
  ForgotPasswordResponseDto,
  ForgotPasswordVerifyOtpDto,
  UpdatePasswordDto,
} from '../dto/login.dto';
@Injectable()
export class LoginService {
  constructor(private readonly loginRepository: LoginRepository) {}
  /**
   * Executes the login stored procedure and returns
   * the response generated by the stored procedure.
   * USP_User_login returns:
   * {
   *   success: boolean,
   *   statusCode: number,
   *   message: string,
   *   Login_Tokens: string | null
   * }
   */
  async login(
    credentials: LoginProcedureRequest,
  ): Promise<LoginResponse> {
    try {
      // Execute the login stored procedure through repository.
      const result = await this.loginRepository.login(credentials);
      // No response returned from database.
      if (!result) {
        throw new InternalServerErrorException(
          this.internalError(),
        );
      }
      // Convert SQL Server JSON string into TypeScript object.
      const response = JSON.parse(result) as unknown;
      // Validate the response structure returned by SQL Server.
      if (!this.isLoginResponse(response)) {
        throw new InternalServerErrorException(
          this.internalError(),
        );
      }
      // Login successful.
      if (response.statusCode === 200) {
        return response;
      }
      // Stored procedure returned an HTTP-style error status.
      if (this.isHttpStatus(response.statusCode)) {
        throw new HttpException(
          response,
          response.statusCode,
        );
      }
      // Unexpected status code.
      throw new InternalServerErrorException(
        this.internalError(),
      );
    } catch (error: unknown) {
      // Preserve HttpException generated from the stored procedure.
      if (error instanceof HttpException) {
        throw error;
      }
      // Convert unexpected errors into HTTP 500.
      throw new InternalServerErrorException(
        this.internalError(),
      );
    }
  }
  /**
   * Validates that the stored procedure returned
   * the expected login response structure.
   */
  private isLoginResponse(
  response: unknown,
): response is LoginResponse {
  if (!response || typeof response !== 'object') {
    return false;
  }

  const value = response as Record<string, unknown>;

  if (
    typeof value.success !== 'boolean' ||
    typeof value.statusCode !== 'number' ||
    typeof value.message !== 'string'
  ) {
    return false;
  }

  const data = value.data;

  if (
    !data ||
    typeof data !== 'object' ||
    Array.isArray(data)
  ) {
    return false;
  }

  const refreshToken = (data as Record<string, unknown>)
    .refreshToken;

  if (value.statusCode === 200) {
    return (
      value.success === true &&
      typeof refreshToken === 'string'
    );
  }

  return (
    value.success === false &&
    (refreshToken === null || refreshToken === undefined)
  );
}
private internalError(): LoginResponse {
  return {
    success: false,
    statusCode: 500,
    message:
      'An unexpected error occurred while processing the login',
    data: {
      refreshToken: null,
    },
  };
}
private isHttpStatus(statusCode: number): boolean {
  return (
    Number.isInteger(statusCode) &&
    statusCode >= 100 &&
    statusCode <= 599
  );
}
  /**
   * Verifies forgot-password OTP.
   */
  async verifyForgotPasswordOtp(
    body: ForgotPasswordVerifyOtpDto,
  ): Promise<ForgotPasswordVerifyOtpResponse> {
    const request = this.validateForgotPasswordOtp(body);
    if (!request) {
      return this.throwForgotPasswordOtpValidation(body);
    }
    try {
      const json =
        await this.loginRepository.verifyForgotPasswordOtp(request);
      if (!json) {
        throw new HttpException(
          this.otpInternalError(),
          500,
        );
      }
      const response = JSON.parse(json) as unknown;
      if (!this.isForgotPasswordOtpResponse(response)) {
        throw new HttpException(
          this.otpInternalError(),
          500,
        );
      }
      if (response.statusCode === 200) {
        return {
          statusCode: 200,
          success: true,
          FP_Token: response.FP_Token,
          message: response.message,
        };
      }
      throw new HttpException(
        {
          statusCode: response.statusCode,
          success: false,
          message: response.message,
        },
        response.statusCode,
      );
    } catch (error: unknown) {
      if (error instanceof HttpException) {
        throw error;
      }
      throw new HttpException(
        this.otpInternalError(),
        500,
      );
    }
  }
  /**
   * Validates forgot-password OTP request.
   */
  private validateForgotPasswordOtp(
    body: ForgotPasswordVerifyOtpDto,
  ): ForgotPasswordVerifyOtpRequest | null {
    if (
      typeof body?.otp_token !== 'string' ||
      typeof body.otp !== 'string' ||
      typeof body.identifier !== 'string' ||
      typeof body.otp_type !== 'string'
    ) {
      return null;
    }
    if (
      !this.isNonEmpty(body.otp) ||
      !this.isNonEmpty(body.otp_token) ||
      !this.isNonEmpty(body.identifier) ||
      !this.isNonEmpty(body.otp_type)
    ) {
      return null;
    }
    if (
      body.otp.length > 20 ||
      body.identifier.length > 10 ||
      body.otp_type.length > 20
    ) {
      return null;
    }
    return {
      otp_token: body.otp_token,
      otp: body.otp,
      identifier: body.identifier,
      otp_type: body.otp_type,
    };
  }
  /**
   * Throws validation error for invalid forgot-password OTP request.
   */
  private throwForgotPasswordOtpValidation(
    body: ForgotPasswordVerifyOtpDto,
  ): never {
    const message = !this.isNonEmpty(body?.otp)
      ? 'Please enter OTP.'
      : !this.isNonEmpty(body.otp_token)
        ? 'Process declined - OTP token missing.'
        : !this.isNonEmpty(body.identifier)
          ? 'Process declined - identifier missing.'
          : !this.isNonEmpty(body.otp_type)
            ? 'Process declined - OTP type missing.'
            : 'Invalid request parameters.';
    throw new HttpException(
      {
        statusCode: 400,
        success: false,
        message,
      },
      400,
    );
  }
  /**
   * Checks whether a value is a non-empty string.
   */
  private isNonEmpty(value: unknown): value is string {
    return (
      typeof value === 'string' &&
      value.trim() !== ''
    );
  }
  /**
   * Validates forgot-password OTP response.
   */
  private isForgotPasswordOtpResponse(
    value: unknown,
  ): value is ForgotPasswordVerifyOtpResponse {
    if (!value || typeof value !== 'object') {
      return false;
    }
    const response =
      value as Partial<ForgotPasswordVerifyOtpResponse>;
    const statuses = new Set([
      200,
      400,
      401,
      403,
      404,
      409,
      410,
      500,
    ]);
    if (
      !statuses.has(response.statusCode as number) ||
      typeof response.success !== 'boolean' ||
      typeof response.message !== 'string'
    ) {
      return false;
    }
    return response.statusCode === 200
      ? response.success &&
          typeof response.FP_Token === 'string' &&
          response.FP_Token.length > 0
      : !response.success;
  }
  /**
   * Standard internal error response for OTP verification.
   */
  private otpInternalError(): ForgotPasswordVerifyOtpResponse {
    return {
      statusCode: 500,
      success: false,
      message:
        'An unexpected error occurred. Please try again later.',
    };
  }
  /**
   * Forgot-password flow.
   */
  async forgotPassword(
    dto: ForgetPasswordDto,
  ): Promise<ForgotPasswordResponseDto> {
    try {
      // Execute the forgot-password stored procedure.
      const result =
        await this.loginRepository.forgotPassword(dto);

      // No response returned from database.
      if (!result) {
        throw new InternalServerErrorException({
          Status: 500,
          Success: false,
          OTP: null,
          Message:
            'An unexpected error occurred while processing the request',
          OtpKey: null,
        });
      }
      // Preserve error status returned by stored procedure.
      if (
        result.Status === 400 ||
        result.Status === 403 ||
        result.Status === 404 ||
        result.Status === 409 ||
        result.Status === 429 ||
        result.Status === 500
      ) {
        throw new HttpException(
          result,
          result.Status,
        );
      }
      // Successful forgot-password response.
      if (result.Status === 200) {
        return result;
      }
      // Unexpected status code.
      throw new InternalServerErrorException({
        Status: 500,
        Success: false,
        OTP: null,
        Message:
          'An unexpected error occurred while processing the request',
        OtpKey: null,
      });
    } catch (error: unknown) {
      // Preserve existing HttpException.
      if (error instanceof HttpException) {
        throw error;
      }
      throw new InternalServerErrorException({
        Status: 500,
        Success: false,
        OTP: null,
        Message:
          'An unexpected error occurred while processing the request',
        OtpKey: null,
      });
    }
  }
  /**
   * Updates the user's password using
   * USP_FP_Update_Password.
   * The stored procedure handles:
   * - FP token validation
   * - User validation
   * - Password update
   * - Session invalidation
   * - Final JSON response
   */
  async updatePassword(
    body: UpdatePasswordDto,
  ): Promise<UpdatePasswordResponse> {
    // Prepare request object expected by repository.
    const request: UpdatePasswordRequest = {
      FP_Token: body.FP_Token,
      new_pwd: body.new_pwd,
    };
    try {
      // Execute password update stored procedure.
      const json =
        await this.loginRepository.updatePassword(request);
      // No response returned from database.
      if (!json) {
        throw new InternalServerErrorException({
          HttpStatus: 500,
          Message:
            'An unexpected error occurred while updating the password.',
        });
      }
      // Convert SQL Server JSON string to object.
      const response =
        JSON.parse(json) as UpdatePasswordResponse;

      // Validate stored procedure response.
      if (
        typeof response.HttpStatus !== 'number' ||
        typeof response.Message !== 'string'
      ) {
        throw new InternalServerErrorException({
          HttpStatus: 500,
          Message:
            'An unexpected error occurred while updating the password.',
        });
      }
      // Successful password update.
      if (response.HttpStatus === 200) {
        return response;
      }
      // Preserve error status returned by stored procedure.
      throw new HttpException(
        response,
        response.HttpStatus,
      );
    } catch (error: unknown) {
      // Preserve existing HttpException.
      if (error instanceof HttpException) {
        throw error;
      }
      // Convert unexpected errors into HTTP 500.
      throw new InternalServerErrorException({
        HttpStatus: 500,
        Message:
          'An unexpected error occurred while updating the password.',
      });
    }
  }
}