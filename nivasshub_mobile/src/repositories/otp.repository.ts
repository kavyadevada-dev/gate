import { Injectable } from '@nestjs/common';

import { connectDB, sql } from '../config/db';

@Injectable()
export class OtpRepository {
  /**
   * Executes the Resend OTP stored procedure.
   *
   * The client sends UID_Enc as a Base64 encoded encrypted
   * User ID. The stored procedure is responsible for:
   *
   * 1. Converting the Base64 value to VARBINARY.
   * 2. Decrypting it using the KTS passphrase.
   * 3. Converting the decrypted value to BIGINT.
   *
   * Therefore, the API must NOT encrypt the UID again.
   */
  async resendOtp(
    uidEnc: string,
    otpType: string,
    identifier: string,
  ): Promise<string | null> {
    try {
      const pool = await connectDB();

      /**
       * Prepare the stored procedure request.
       *
       * The current SP expects UID_Enc as VARCHAR(200),
       * not VARBINARY(MAX).
       */
      const request = pool
        .request()
        .input(
          'UID_Enc',
          sql.VarChar(200),
          uidEnc,
        )
        .input(
          'OTPType',
          sql.VarChar(50),
          otpType,
        )
        .input(
          'identifier',
          sql.VarChar(50),
          identifier,
        )
        .input(
          'MaxResendLimit',
          sql.Int,
          5,
        )
        .input(
          'ResendCooldownSeconds',
          sql.Int,
          30,
        )
        .input(
          'OTPValidityMinutes',
          sql.Int,
          15,
        )
        .output(
          'ResponseJSON',
          sql.NVarChar(sql.MAX),
        );

      /**
       * Execute the stored procedure.
       *
       * The SP generates the OTP, stores it encrypted,
       * applies resend rules and builds ResponseJSON.
       */
      const result = await request.execute(
        'dbo.usp_ResendOTP',
      );

      /**
       * Return the JSON generated by the stored procedure.
       */
      return result.output?.ResponseJSON ?? null;
    } catch (error) {
      console.error(
        'Error executing dbo.usp_ResendOTP:',
        error,
      );

      throw error;
    }
  }
}