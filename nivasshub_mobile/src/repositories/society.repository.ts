import { Injectable } from '@nestjs/common';
import { connectDB, sql } from '../config/db';
import { AddUserToSocietyDto } from '../dto/society.dto';
/**
 * Repository responsible for all database operations
 * related to Society.
 * This repository communicates directly with SQL Server
 * through the Society stored procedure.
 */
@Injectable()
export class SocietyRepository {
  /**
   * Executes the stored procedure to retrieve the complete
   * active society structure.
   * Stored Procedure:
   * dbo.USP_Registration_Get_Society_Details
   * The procedure returns:
   * 1. JsonResponse - complete API response as JSON.
   * 2. @StatusCode  - HTTP status code returned by the procedure.
   * @param societyId - Unique ID of the society.
   * @returns JsonResponse and StatusCode from the procedure.
   */
  async getSocietyDetails(
    societyId: number,
  ): Promise<{
    jsonResponse: string | null;
    statusCode: number | null;
  }> {
    try {
      // Establish a connection with the SQL Server database.
      const pool = await connectDB();
       // Execute the Society Details stored procedure.
      const request = pool
        .request()
        .input(
          'socid',
          sql.BigInt,
          societyId,
        );
      /**
       * @StatusCode is an OUTPUT parameter.
       * We initialize it with NULL because the stored procedure
       * itself determines the final status code.
       */
      request.output(
        'StatusCode',
        sql.Int,
      );
      // Execute the stored procedure.
      const result = await request.execute(
        'dbo.USP_Registration_Get_Society_Details',
      );
      /**
       * The stored procedure returns a single-row result set
       * containing one column:
       * JsonResponse
       * We read the column explicitly instead of rebuilding
       * the response in the repository.
       */
      const jsonResponse =
        result.recordset &&
        result.recordset.length > 0
          ? result.recordset[0].JsonResponse ?? null
          : null;
      /**
       * Read the HTTP status code returned through the
       * stored procedure OUTPUT parameter.
       */
      const statusCode =
        result.output?.StatusCode ?? null;
      // Return both values to the service layer.
      return {
        jsonResponse,
        statusCode,
      };
    } catch (error) {
      /**
       * Log the actual database error on the server.
       * Internal database details should not be returned
       * directly to the frontend.
       */
      console.error(
        'Error executing USP_Registration_Get_Society_Details:',
        error,
      );
      // Pass the database error to the service layer.
      throw error;
    }
  }
  /**
 * Executes the Add Society master data stored procedure.
 * Stored Procedure:
 * dbo.USP_Add_Society_Get
 * The procedure validates the user's session and returns
 * the complete Add Society master data response as JSON.
 * @param userToken - User session/refresh token.
 * @param ipAddress - Client IP address.
 * @param deviceInfo - Client device information.
 * @returns JSON response generated by the stored procedure.
 */
async getAddSocietyMasterData(
  userToken: string,
  ipAddress: string,
  deviceInfo: string,
): Promise<string | null> {
  try {
    // Establish a connection with SQL Server.
    const pool = await connectDB();
    // Execute the Add Society master data stored procedure.
    const result = await pool
      .request()
      .input(
        'user_token',
        sql.VarChar(sql.MAX),
        userToken,
      )
      .input(
        'ipadd',
        sql.VarChar(500),
        ipAddress,
      )
      .input(
        'dinfo',
        sql.VarChar(500),
        deviceInfo,
      )
      .execute('dbo.USP_Add_Society_Get');
    /**
     * The stored procedure returns one row containing
     * the complete JSON response in the Result column.
     */
    if (
      !result.recordset ||
      result.recordset.length === 0
    ) {
      return null;
    }
    return result.recordset[0].Result ?? null;
  } catch (error) {
    // Log database errors on the server.
    console.error(
      'Error executing dbo.USP_Add_Society_Get:',
      error,
    );
    // Pass the error to the service layer.
    throw error;
  }
}
  /**
   * Adds a registered user to a society unit.
   * Executes the stored procedure and returns its JSON response.
   */
  async addUserToSociety(
    dto: AddUserToSocietyDto,
    ipAddress: string,
    deviceInfo: string,
  ): Promise<string | null> {
    try {
      const pool = await connectDB();
      const result = await pool
        .request()
        .input('user_token', sql.VarChar(sql.MAX), dto.user_token)
        .input('cont_code', sql.BigInt, dto.cont_code)
        .input('state_code', sql.BigInt, dto.state_code)
        .input('city', sql.VarChar(100), dto.city)
        .input('soc_id', sql.BigInt, dto.soc_id)
        .input('tower_id', sql.BigInt, dto.tower_id)
        .input('floor', sql.BigInt, dto.floor)
        .input('unitid', sql.BigInt, dto.unitid)
        .input('user_type', sql.BigInt, dto.user_type)
        .input('user_sub_role', sql.BigInt, dto.user_sub_role ?? null)
        .input('user_cat', sql.BigInt, dto.user_cat ?? null)
        .input('documentid', sql.BigInt, dto.documentid)
        .input('documenturl', sql.VarBinary(sql.MAX), null)
        .input('ipadd', sql.VarChar(200), ipAddress)
        .input('dinfo', sql.VarChar(200), deviceInfo)
        .execute('dbo.USP_User_Add_Society');
      // Return the JSON response column from the procedure.
      const row = result.recordset?.[0];
      if (!row) return null;
      const response = row.ResponseJson ?? Object.values(row)[0];
      return typeof response === 'string' ? response : null;
    } catch (error) {
      console.error('Error executing dbo.USP_User_Add_Society:', error);
      throw error;
    }
  }
  // Get Countries, States, and Societies
async getCountriesStatesSocieties(sessionToken: string): Promise<string | null> {
  try {
    // Establish a connection to the database
    const pool = await connectDB();
    // Pass the session token and execute the stored procedure
    const result = await pool
      .request()
      .input('session_Token', sql.VarChar(500), sessionToken)
      .execute('dbo.USP_Add_Society_Get_Countries_States_Societies');
    // Return null if the stored procedure returns no records
    if (!result.recordset || result.recordset.length === 0) {
      return null;
    }
    // Return the JSON response from the stored procedure
    return result.recordset[0].response ?? null;
  } catch (error) {
    // Log the error if stored procedure execution fails
    console.error('Error executing USP_Add_Society_Get_Countries_States_Societies:', error);
    throw error;
  }
}
}